#!/usr/bin/env python3
"""Package license notices and the source inputs used by a Disproid build."""
import argparse
import hashlib
import html
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tarfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
CPP = ROOT / 'android/app/src/main/cpp'
OPENSSL = ROOT / 'android/native-deps/src/openssl'


def git(*args, cwd=ROOT):
    return subprocess.check_output(['git', '-C', str(cwd), *args]).decode().strip()


def identity():
    if not (ROOT / '.git').exists():
        recorded = json.loads((ROOT / 'SOURCE_BUILD.json').read_text())
        changed = any(not (ROOT / path).is_file() or hashlib.sha256((ROOT / path).read_bytes()).hexdigest() != sha
                      for path, sha in recorded['source_hashes'].items())
        # Gradle / CMake / SwiftPM also discover newly added source and resource files.
        added = any(path.relative_to(ROOT).as_posix() not in recorded['source_hashes']
                    for base in [ROOT / 'android/app/src', ROOT / 'mac/Sources']
                    for path in base.rglob('*') if path.is_file() and 'prebuilt' not in path.parts)
        dirty = recorded['dirty'] or changed or added or not openssl_archive_matches(OPENSSL)
        label = f'local-{recorded["commit"][:12]}' if dirty else recorded['label']
        return {'commit': recorded['commit'], 'dirty': dirty, 'label': label,
                'source_archive': f'disproid-source-{label}.tar.gz'}
    revision = git('rev-parse', 'HEAD')
    dirty = bool(git('status', '--porcelain', '--untracked-files=normal'))
    release = os.environ.get('GITHUB_REF_NAME') if os.environ.get('GITHUB_REF_TYPE') == 'tag' else None
    label = release or f'local-{revision[:12]}'
    return {'commit': revision, 'dirty': dirty, 'label': label,
            'source_archive': f'disproid-source-{label}.tar.gz'}


def openssl_archive_matches(path):
    manifest = json.loads((path / 'SOURCE_ARCHIVE.json').read_text())
    return manifest['tag'] == 'openssl-3.3.2' and all(
        (path / name).is_file() and hashlib.sha256((path / name).read_bytes()).hexdigest() == sha
        for name, sha in manifest['source_hashes'].items())


def source_notice(build):
    if build['label'].startswith('local-'):
        location = 'ローカル検証用ビルドです。未コミット変更を含む場合、下記コミットの公開ソースと同一ではありません。\n'
    else:
        location = ('同じ Release の次の対応ソース資材を取得してください。\n'
                    f"https://github.com/k02miu/disproid/releases/download/{build['label']}/{build['source_archive']}\n")
    return (f"Disproid source / 対応ソース\n\nCommit: {build['commit']}\nDirty: {build['dirty']}\n"
            f"Archive: {build['source_archive']}\n\n{location}\n"
            f"リポジトリ: https://github.com/k02miu/disproid/tree/{build['commit']}\n"
            '配布手順: DISTRIBUTION.md\n'
            '対応ソース資材にはアプリ、vendor コード、使用した OpenSSL ソース、\n'
            'Gradle ランタイム依存のソース JAR とビルド手順を含めます。\n'
            '変更・再ビルド・LGPL ライブラリの差し替えと再リンクには同梱の手順を使えます。\n'
            '本ソフトウェアは無保証です。再配布・改変の条件は同梱 LICENSE と各第三者ライセンスを参照してください。\n')


def extract_notices(archive, destination, prefix=''):
    with zipfile.ZipFile(archive) as z:
        for name in z.namelist():
            if name.endswith('/'):
                continue
            basename = Path(name).name.lower()
            if re.search(r'(^|[-_.])(license|licence|notice|copying)([-_.]|$)', basename):
                # Flatten only the archive path, never trust it as a filesystem path.
                filename = prefix + name.replace('/', '__').replace('\\', '__')
                destination.mkdir(parents=True, exist_ok=True)
                (destination / filename).write_bytes(z.read(name))
            if name == 'classes.jar':
                extract_notices(io.BytesIO(z.read(name)), destination, 'classes__')


def notices(output, artifacts):
    # Only replace this task's generated directory, not user source files.
    if output.exists():
        if not (output / '.generated-by-disproid').is_file():
            raise SystemExit('Refusing to replace a directory not generated by Disproid.')
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / '.generated-by-disproid').touch()
    paths = ['LICENSE', 'THIRD_PARTY_NOTICES.md', 'DISTRIBUTION.md',
             'licenses/README.md', 'licenses/LGPL-2.1.txt', 'licenses/Apache-2.0.txt',
             'android/app/src/main/cpp/airplay/llhttp/LICENSE-MIT',
             'android/app/src/main/cpp/airplay/playfair/LICENSE.md',
             'android/app/src/main/cpp/third_party/libplist/COPYING']
    for path in paths:
        target = output / path
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / path, target)
    headers = []
    for vendor in [CPP / 'airplay', CPP / 'third_party/libplist']:
        for path in sorted(vendor.rglob('*')):
            if path.suffix not in {'.c', '.h', '.cpp'}:
                continue
            text = path.read_text(errors='strict')
            match = re.match(r'\s*(/\*.*?\*/)', text, re.S)
            if match:
                headers.append(f'=== {path.relative_to(ROOT)} ===\n{match[1]}\n')
    (output / 'VENDORED_NOTICES.txt').write_text('\n'.join(headers))
    if OPENSSL.exists():
        for name in ['LICENSE.txt', 'NOTICE', 'AUTHORS.md']:
            path = OPENSSL / name
            if path.is_file():
                dest = output / 'openssl' / name
                dest.parent.mkdir(exist_ok=True)
                shutil.copyfile(path, dest)
    resolved = []
    for artifact in artifacts:
        path = Path(artifact)
        resolved.append({'artifact': path.name, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
        extract_notices(path, output / 'runtime-notices' / path.name)
    if resolved:
        (output / 'runtime-dependencies.json').write_text(json.dumps(resolved, indent=2) + '\n')
    build = identity()
    (output / 'SOURCES.txt').write_text(source_notice(build))
    (output / 'build.json').write_text(json.dumps(build, indent=2) + '\n')
    links = []
    for number, path in enumerate(sorted(output.rglob('*'))):
        if not path.is_file() or path.name.startswith('.'):
            continue
        relative = path.relative_to(output).as_posix()
        view = output / 'view' / f'{number}.html'
        view.parent.mkdir(exist_ok=True)
        view.write_text('<!doctype html><html lang="ja"><meta charset="utf-8"><meta name="viewport" content="width=device-width">'
                        '<style>body{font:16px system-ui;margin:20px}pre{white-space:pre-wrap;overflow-wrap:anywhere}</style>'
                        f'<title>{html.escape(relative)}</title><a href="../index.html">一覧へ</a>'
                        f'<h1>{html.escape(relative)}</h1><pre>{html.escape(path.read_text(errors="replace"))}</pre></html>')
        links.append(f'<li><a href="view/{number}.html">{html.escape(relative)}</a></li>')
    index = ('<!doctype html><html lang="ja"><meta charset="utf-8"><meta name="viewport" content="width=device-width">'
             '<title>Disproid — ライセンスとソース</title><style>body{font:16px system-ui;margin:24px}li{margin:12px 0}pre{white-space:pre-wrap;overflow-wrap:anywhere}</style>'
             '<h1>ライセンスとソース</h1><p>Disproid は GPL-3.0 で公開されています。無保証です。</p>'
             '<p>以下の原文はオフラインで閲覧できます。第三者コードの各条件も参照してください。</p>'
             f'<pre>{html.escape(source_notice(build))}</pre>'
             f'<p><a href="https://github.com/k02miu/disproid/tree/{build["commit"]}">ソースリポジトリ</a></p>'
             f'<ul>{"".join(links)}</ul></html>')
    (output / 'index.html').write_text(index)


def package_source(output, dependencies, allow_dirty):
    build = identity()
    if build['dirty'] and not allow_dirty:
        raise SystemExit('Refusing release source archive from a dirty tree; use --allow-dirty only for local verification.')
    if git('describe', '--tags', '--exact-match', cwd=OPENSSL) != 'openssl-3.3.2':
        raise SystemExit('OpenSSL source must be the exact openssl-3.3.2 tag.')
    if git('diff', 'HEAD', '--', cwd=OPENSSL):
        raise SystemExit('OpenSSL tracked sources differ from the tag.')
    dependency_manifest = json.loads((dependencies / 'dependencies.json').read_text())
    if not dependency_manifest:
        raise SystemExit('No resolved runtime dependency sources found.')
    for dep in dependency_manifest:
        for name in ['source', 'pom']:
            path = dependencies / dep[name]
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != dep[name + '_sha256']:
                raise SystemExit(f'Missing or changed dependency {name}: {dep["coordinate"]}')
    output.mkdir(parents=True, exist_ok=True)
    path = output / build['source_archive']
    paths = subprocess.check_output(['git', 'ls-files', '-z'], cwd=ROOT).split(b'\0')
    if allow_dirty:
        paths += subprocess.check_output(['git', 'ls-files', '-z', '--others', '--exclude-standard'], cwd=ROOT).split(b'\0')
    source_hashes = {}
    with tarfile.open(path, 'w:gz') as archive:
        def add_json(name, data):
            payload = json.dumps(data, indent=2).encode()
            entry = tarfile.TarInfo('disproid/' + name)
            entry.size = len(payload)
            archive.addfile(entry, io.BytesIO(payload))
        for raw in sorted(set(paths)):
            if not raw:
                continue
            rel = raw.decode()
            if rel.startswith(('.build/', '.forge/', '.forge.json')):
                continue
            archive.add(ROOT / rel, arcname='disproid/' + rel, recursive=False)
            if (ROOT / rel).is_file():
                source_hashes[rel] = hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()
        openssl_tar = subprocess.check_output(['git', 'archive', 'HEAD'], cwd=OPENSSL)
        openssl_hashes = {}
        with tarfile.open(fileobj=io.BytesIO(openssl_tar)) as upstream:
            for member in upstream:
                if member.isfile():
                    openssl_hashes[member.name] = hashlib.sha256(upstream.extractfile(member).read()).hexdigest()
                member.name = 'disproid/android/native-deps/src/openssl/' + member.name
                archive.addfile(member, upstream.extractfile(member) if member.isfile() else None)
        add_json('android/native-deps/src/openssl/SOURCE_ARCHIVE.json', {
            'tag': 'openssl-3.3.2', 'commit': git('rev-parse', 'HEAD', cwd=OPENSSL), 'source_hashes': openssl_hashes})
        archive.add(dependencies, arcname='disproid/dependency-sources')
        add_json('SOURCE_BUILD.json', {**build, 'openssl_commit': git('rev-parse', 'HEAD', cwd=OPENSSL), 'source_hashes': source_hashes})
    print(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='command', required=True)
    notice = commands.add_parser('notices')
    notice.add_argument('--output', type=Path, required=True)
    notice.add_argument('--artifact', action='append', default=[])
    source = commands.add_parser('source')
    source.add_argument('--output', type=Path, default=ROOT / 'dist')
    source.add_argument('--dependencies', type=Path, default=ROOT / 'android/app/build/oss-sources')
    source.add_argument('--allow-dirty', action='store_true')
    verify = commands.add_parser('verify-openssl')
    verify.add_argument('path', type=Path)
    args = parser.parse_args()
    if args.command == 'notices':
        notices(args.output, args.artifact)
    elif args.command == 'source':
        package_source(args.output, args.dependencies, args.allow_dirty)
    elif not openssl_archive_matches(args.path):
        raise SystemExit('OpenSSL source archive files do not match their manifest.')


if __name__ == '__main__':
    main()
